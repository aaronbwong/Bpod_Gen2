function setValveStimulus(hiFiModule, amplitude, frequency, enabled)
    if enabled
        hiFiModule.SynthAmplitude = 0;
        hiFiModule.SynthWaveform = 'Sine';
        hiFiModule.SynthFrequency = frequency;
        hiFiModule.SynthAmplitude = amplitude;
    else
        hiFiModule.SynthAmplitude = 0;
    end
end

% Clear counters function
function clearCounters(fig)
    data = guidata(fig);
    data.leftCount = 0;
    data.rightCount = 0;
    data.totalCount = 0;
    data.leftCountLabel.Text = '0 μL';
    data.rightCountLabel.Text = '0 μL';
    data.totalCountLabel.Text = '0 μL';
    data.statusLabel.Text = 'Counters cleared';
    data.statusLabel.BackgroundColor = [0.95 0.95 0.95];
    guidata(fig, data);
end

% Close GUI function - FIXED: now accepts fig as input argument
function closeGUI(fig)
    % Stop Bpod protocol
    try
        RunProtocol('Stop');
    catch
        % Ignore errors
    end
    delete(fig);
end

function updateValveTime(fig, whichValve)
    data = guidata(fig);
    switch whichValve
        case 'left'
            newDropSize_ul = data.leftDoseField.Value;
            newValveTime_s = BpodLiquidCalibration('GetValveTimes', newDropSize_ul, 1);
            data.leftDurationField.Value = 1000*newValveTime_s;
        case 'right'
            newDropSize_ul = data.rightDoseField.Value;
            newValveTime_s = BpodLiquidCalibration('GetValveTimes', newDropSize_ul, 2);
            data.rightDurationField.Value = 1000*newValveTime_s;

    end
end
