fig.CloseRequestFcn = @(src,event) closeGUI(fig);
fig.KeyPressFcn = @(src, event) onKeyPress(src, event);


function onKeyPress(fig, event)
    % event.Key contains the name of the key pressed
    % event.Modifier contains any modifier keys (e.g., 'shift', 'control')
    keyName = event.Key;
    modifiers = strjoin(event.Modifier, '+');

switch keyName
    case {'a'}
        leftDispense(fig)
    case {'d'}
        rightDispense(fig)
end
%     if isempty(modifiers)
%         statusLabel.Text = sprintf('You pressed: %s', keyName);
%     else
%         statusLabel.Text = sprintf('You pressed: %s + %s', modifiers, keyName);
%     end
end

% Left dispense function
function leftDispense(fig)
    data = guidata(fig);
    addStimulus = data.leftStimulusCheckBox.Value;
    try
        dose = data.leftDoseField.Value;
        drops = data.leftDropField.Value;
        ValveTime_s = data.leftDurationField.Value ./ 1000;
        
        data.statusLabel.Text = 'Left dispensing in progress...';
        data.statusLabel.BackgroundColor = [1 1 0.8];
        drawnow;

        if addStimulus
            setValveStimulus(data.HiFiModule, data.leftVibAmpField.Value, ...
                             data.leftVibFreqField.Value, true);
        end
        
        % Call dispense function
%         Dispense(1, dose, drops);
        DispenseByDur(1, ValveTime_s, drops);

        if addStimulus
            setValveStimulus(data.HiFiModule, 0, 0, false);
            addStimulus = false;
        end
        
        % Update counters
        dispensedVolume = dose * drops;
        data.leftCount = data.leftCount + dispensedVolume;
        data.totalCount = data.totalCount + dispensedVolume;
        guidata(fig, data);
        
        data.leftCountLabel.Text = [num2str(data.leftCount) ' μL'];
        data.totalCountLabel.Text = [num2str(data.totalCount) ' μL'];
        
        data.statusLabel.Text = sprintf('Left dispense complete: %.1f μL × %d', dose, drops);
        data.statusLabel.BackgroundColor = [0.8 1 0.8];
        
    catch ME
        if addStimulus
            try
                setValveStimulus(data.HiFiModule, 0, 0, false);
            catch
            end
        end
        data.statusLabel.Text = ['Error: ' ME.message];
        data.statusLabel.BackgroundColor = [1 0.8 0.8];
    end
end

% Right dispense function
